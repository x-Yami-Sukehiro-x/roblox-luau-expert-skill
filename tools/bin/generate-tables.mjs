#!/usr/bin/env node
// Regenerate the verified/ reference tables from the vendored dump.
//
// These files are the router's grep targets. They are derived data - never
// hand-edit them; change the dump or this generator and re-run.
//
// Usage:
//   node tools/bin/generate-tables.mjs [--out <dir>] [--check]
//
// --check regenerates into memory and exits 1 if anything on disk differs,
// which is how you prove the committed tables still match the dump.

import { writeFileSync, readFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { loadDump, loadDatatypes, isUnreachable, isWriteGated, REPO_ROOT } from "./lib/dump.mjs";

const DEFAULT_OUT = join(
  REPO_ROOT,
  ".claude", "skills", "roblox-luau-expert", "references", "verified"
);

// Replacements the dump does not record. Only unambiguous ones belong here; a
// wrong replacement is worse than a blank cell.
const REPLACEMENTS = {
  Remove: "Instance:Destroy",
  BodyVelocity: "LinearVelocity",
  BodyAngularVelocity: "AngularVelocity",
  BodyPosition: "AlignPosition",
  BodyGyro: "AlignOrientation",
  BodyForce: "VectorForce",
  BodyThrust: "VectorForce",
  RocketPropulsion: "LinearVelocity plus AlignOrientation",
  FindPartOnRay: "WorldRoot:Raycast",
  FindPartOnRayWithIgnoreList: "WorldRoot:Raycast with FilterDescendantsInstances",
  FindPartOnRayWithWhitelist: "WorldRoot:Raycast with FilterType = Include",
  FindPartsInRegion3: "WorldRoot:GetPartBoundsInBox",
  FindPartsInRegion3WithIgnoreList: "WorldRoot:GetPartBoundsInBox with OverlapParams",
  FindPartsInRegion3WithWhiteList: "WorldRoot:GetPartBoundsInBox with OverlapParams",
  Chat: "TextChatService",
  LoadCharacterBlocking: "Player:LoadCharacter",
  GetGlobalDataStore: "DataStoreService:GetDataStore with an explicit name",
  FilteringEnabled: "always on now; the property is inert",
  CreateHumanoidModelFromDescription: "Players:CreateHumanoidModelFromDescriptionAsync",
  CreateDockWidgetPluginGui: "Plugin:CreateDockWidgetPluginGuiAsync",
  PlayerOwnsAsset: "MarketplaceService:UserOwnsGamePassAsync for passes",
  TeleportToPlaceInstance: "TeleportService:TeleportAsync with TeleportOptions",
  TeleportToSpawnByName: "TeleportService:TeleportAsync with TeleportOptions",
  CornerRadius: "the four per-corner UICorner radii",
  CopyRegion: "Terrain:WriteVoxels",
  PasteRegion: "Terrain:WriteVoxels",
};

const today = new Date().toISOString().slice(0, 10);

function header(dump, title) {
  return (
    `<!-- GENERATED by tools/bin/generate-tables.mjs - do not hand-edit. -->\n` +
    `<!-- Roblox API dump ${dump.version} - generated ${today} -->\n\n` +
    `# ${title}\n\n`
  );
}

function buildApiIndex(dump) {
  const names = [...dump.memberIndex.keys()].sort((a, b) => a.localeCompare(b));
  return (
    `# Roblox API flat index - dump ${dump.version} - generated ${today}\n` +
    `# One Class.Member per line. Grep target for existence checks.\n` +
    `# Check declaring class/inheritance and datatypes before concluding absence from this snapshot.\n` +
    `# Datatypes (CFrame, TweenInfo, SharedTable...) are NOT here - see datatype-index.txt.\n` +
    names.join("\n") +
    "\n"
  );
}

function buildHierarchy(dump) {
  // api-index.txt lists each member against the class that DECLARES it, so
  // `Workspace.Raycast` is absent from it and `WorldRoot.Raycast` is not.
  // Without the chain, a grep for the first one concludes the API is invented.
  const lines = [];
  for (const [name, record] of [...dump.classes].sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`${name} : ${record.superclass ?? "-"}`);
  }
  return (
    `# Roblox class hierarchy - dump ${dump.version} - generated ${today}\n` +
    `# One 'Class : Superclass' per line; '-' is the root.\n` +
    `# A member absent from api-index.txt under one class may be declared on a parent.\n` +
    `# ${dump.classes.size} classes.\n` +
    lines.join("\n") +
    "\n"
  );
}

function buildGuiClasses(dump) {
  // The three GUI class sets lib/gui-model.mjs derives from the dump at
  // runtime, written out so tools/py/ui_lint.py can read the same sets without
  // parsing a megabyte of API dump in a sandbox with no Node.
  const descendantsOf = (root) => {
    const names = [];
    for (const [name] of dump.classes) {
      let current = name;
      while (current) {
        if (current === root && name !== root) { names.push(name); break; }
        current = dump.classes.get(current)?.superclass;
      }
    }
    return names.sort();
  };
  const lines = [];
  for (const root of ["GuiObject", "UIBase", "LayerCollector"]) {
    for (const name of descendantsOf(root)) lines.push(`${root} ${name}`);
  }
  return (
    `# Roblox GUI class sets - dump ${dump.version} - generated ${today}\n` +
    `# One 'Root Class' per line: GuiObject, UIBase or LayerCollector.\n` +
    `# Consumed by tools/py/ui_lint.py, which cannot parse the dump itself.\n` +
    lines.join("\n") +
    "\n"
  );
}

function buildEnumIndex(dump) {
  // Enums were the one part of the dump with no flat index, so
  // `Enum.EasingStyle.Smooth` - which does not exist - was unfalsifiable by
  // grep while `Humanoid.SuperJump` was not. Both are the same mistake.
  const lines = [];
  for (const [name, record] of [...dump.enums].sort((a, b) => a[0].localeCompare(b[0]))) {
    for (const item of record.items.keys()) lines.push(`Enum.${name}.${item}`);
  }
  return (
    `# Roblox enum flat index - dump ${dump.version} - generated ${today}\n` +
    `# One Enum.Type.Item per line. Grep target for existence checks.\n` +
    `# Absent from this file means the enum item is not in this dump snapshot.\n` +
    `# ${dump.enums.size} enums, ${lines.length} items.\n` +
    lines.join("\n") +
    "\n"
  );
}

function buildDatatypeIndex(dump) {
  const datatypes = loadDatatypes();
  const lines = [];
  for (const dt of [...datatypes.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    for (const rec of dt.members.values()) lines.push(rec.qualified);
  }
  lines.sort((a, b) => a.localeCompare(b));
  return (
    `# Roblox datatype flat index - generated ${today}\n` +
    `# Source: tools/api-dump/datatypes (vendored from Roblox/creator-docs).\n` +
    `#\n` +
    `# The API dump covers classes and enums ONLY. CFrame, Vector3, TweenInfo,\n` +
    `# RaycastParams, SharedTable and 43 other datatypes are absent from it\n` +
    `# entirely, so a claim about one cannot be checked there. This is that\n` +
    `# check.\n` +
    lines.join("\n") +
    "\n"
  );
}

function buildDeprecated(dump) {
  const byClass = new Map();
  let count = 0;
  for (const cls of dump.classes.values()) {
    const hits = [...cls.members.values()].filter((m) => m.deprecated);
    if (!hits.length) continue;
    byClass.set(cls.name, hits);
    count += hits.length;
  }

  let out = header(dump, "Deprecated Roblox APIs");
  out +=
    "Every `[Deprecated]` entry in the dump, grouped by class. Writing any of these\n" +
    "into new code is a defect. Grep this file for a name before using it; do not\n" +
    "read it top to bottom.\n\n" +
    "**Replacement** is filled in where the mapping is unambiguous. A blank cell\n" +
    "means the dump marks it deprecated but offers no direct successor - check the\n" +
    "Creator Hub before substituting anything.\n\n" +
    "> Deprecated is not the same as superseded. `RunService.Stepped`,\n" +
    "> `.RenderStepped` and `.Heartbeat` carry **no** `[Deprecated]` flag and are\n" +
    "> therefore absent from this file: they are older names for points that still\n" +
    "> exist. Calling them a defect in review is a false positive.\n\n" +
    `**${count} deprecated members across ${byClass.size} classes.**\n\n`;

  for (const name of [...byClass.keys()].sort((a, b) => a.localeCompare(b))) {
    out += `## ${name}\n\n| Member | Kind | Replacement |\n|---|---|---|\n`;
    for (const m of byClass.get(name).sort((a, b) => a.name.localeCompare(b.name))) {
      out += `| \`${m.name}\` | ${m.kind} | ${REPLACEMENTS[m.name] ?? ""} |\n`;
    }
    out += "\n";
  }
  return out;
}

function buildSecurity(dump) {
  const both = [];
  const readOnlyGate = [];
  const writeOnlyGate = [];

  for (const cls of dump.classes.values()) {
    for (const m of cls.members.values()) {
      const a = m.annotations;
      if (a.security) both.push(m);
      else if (a.readSecurity && a.writeSecurity) both.push(m);
      else if (a.readSecurity) readOnlyGate.push(m);
      else if (a.writeSecurity) writeOnlyGate.push(m);
    }
  }

  const total = both.length + readOnlyGate.length + writeOnlyGate.length;
  let out = header(dump, "Security-tagged Roblox APIs");
  out +=
    "Members the engine gates behind a security level. **This is the table that stops\n" +
    "you recommending an API a normal game script cannot reach.** The canonical\n" +
    "example: `Workspace.AuthorityMode` is real, but `RobloxScript`-gated - a\n" +
    "Script or LocalScript reading it gets an error, not a value.\n\n" +
    "The dump distinguishes **which direction** is gated, and the difference matters:\n" +
    "`Workspace.StreamingEnabled` is readable by any script and `Plugin`-gated for\n" +
    "writes only. Reporting that as simply \"Plugin\" would be wrong.\n\n" +
    `**${total} gated members.**\n\n`;

  const section = (title, list, note) => {
    if (!list.length) return "";
    let s = `## ${title} (${list.length})\n\n${note}\n\n| Member | Level | Kind |\n|---|---|---|\n`;
    for (const m of list.sort((a, b) => a.qualified.localeCompare(b.qualified))) {
      const a = m.annotations;
      const level = a.security ?? a.readSecurity ?? a.writeSecurity ?? "?";
      s += `| \`${m.qualified}\` | ${level} | ${m.kind} |\n`;
    }
    return `${s}\n`;
  };

  out += section(
    "Gated for read and write",
    both,
    "A normal script cannot read *or* write these."
  );
  out += section(
    "Gated for read only",
    readOnlyGate,
    "Writable by a normal script, but reading is gated."
  );
  out += section(
    "Gated for write only",
    writeOnlyGate,
    "Readable by any script; the write is what needs elevation."
  );
  return out;
}

function buildParallel(dump) {
  const safe = [];
  const unsafe = [];
  for (const cls of dump.classes.values()) {
    for (const m of cls.members.values()) {
      if (m.annotations.parallel === "Safe") safe.push(m.qualified);
      else if (m.annotations.parallel === "Unsafe") unsafe.push(m.qualified);
    }
  }
  safe.sort((a, b) => a.localeCompare(b));
  unsafe.sort((a, b) => a.localeCompare(b));

  let out = header(dump, "Parallel Luau safety");
  out +=
    "The dump marks a small set of members with an explicit parallel-execution\n" +
    "verdict. Under `task.desynchronize()` inside an `Actor`:\n\n" +
    "- **Safe** - callable while desynchronized.\n" +
    "- **Unsafe** - must not be called in parallel. `task.synchronize()` first.\n\n" +
    "Anything **not listed here** is unmarked, which is not a promise of safety.\n" +
    "Treat unmarked DataModel writes as serial-only.\n\n";
  out += `## Explicitly Unsafe (${unsafe.length})\n\n`;
  out += "These are the ones worth memorising - several are exactly what UI code\nreaches for inside an Actor.\n\n";
  for (const q of unsafe) out += `- \`${q}\`\n`;
  out += `\n## Explicitly Safe (${safe.length})\n\n`;
  for (const q of safe) out += `- \`${q}\`\n`;
  return `${out}\n`;
}

function buildCapabilities(dump) {
  const counts = new Map();
  for (const cls of dump.classes.values()) {
    for (const m of cls.members.values()) {
      for (const cap of m.annotations.capabilities) {
        counts.set(cap, (counts.get(cap) ?? 0) + 1);
      }
    }
  }
  const rows = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

  let out = header(dump, "Script capabilities");
  out +=
    "Roblox's sandboxed-container system gates APIs behind named capabilities. A\n" +
    "script inside a container with `Sandboxed` set only reaches APIs whose\n" +
    "capability the container grants. Outside a sandboxed container these tags do\n" +
    "not restrict anything - but they are the best available map of which subsystem\n" +
    "each API belongs to, which is useful when deciding what a module should own.\n\n" +
    "Sorted by how many API members carry the capability.\n\n" +
    `**${rows.length} capabilities.**\n\n| Capability | Members |\n|---|---|\n`;
  for (const [cap, n] of rows) out += `| \`${cap}\` | ${n} |\n`;
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const outIndex = args.indexOf("--out");
  const outDir = outIndex >= 0 ? args[outIndex + 1] : DEFAULT_OUT;

  const dump = loadDump();
  const files = {
    "api-index.txt": buildApiIndex(dump),
    "datatype-index.txt": buildDatatypeIndex(dump),
    "enum-index.txt": buildEnumIndex(dump),
    "class-hierarchy.txt": buildHierarchy(dump),
    "gui-classes.txt": buildGuiClasses(dump),
    "deprecated-apis.md": buildDeprecated(dump),
    "security-tagged-apis.md": buildSecurity(dump),
    "parallel-safety.md": buildParallel(dump),
    "script-capabilities.md": buildCapabilities(dump),
  };

  if (!check && !existsSync(outDir)) mkdirSync(outDir, { recursive: true });

  let drift = 0;
  for (const [name, content] of Object.entries(files)) {
    const path = join(outDir, name);
    if (check) {
      // The generated-on line changes every day and is not content drift.
      const strip = (s) => s.replace(/generated \d{4}-\d{2}-\d{2}/g, "generated <date>");
      const existing = existsSync(path) ? readFileSync(path, "utf8") : "";
      if (strip(existing.replace(/^﻿/, "")) !== strip(content)) {
        console.log(`DRIFT  ${name}`);
        drift += 1;
      }
      continue;
    }
    writeFileSync(path, content, "utf8");
    const lines = content.split("\n").length;
    console.log(`wrote ${name}  (${lines} lines)`);
  }

  if (check) {
    console.log(
      drift
        ? `\n${drift} file(s) differ from what the dump produces. Run without --check.`
        : `\nAll tables match dump ${dump.version}.`
    );
    if (drift) process.exitCode = 1;
  }
}

main();
