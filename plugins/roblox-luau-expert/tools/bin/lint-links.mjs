function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (entry.endsWith(".md")) out.push(full);
  }
  return out;
}

function hasFileExtension(candidate) {
  const dot = candidate.lastIndexOf(".");
  if (dot < 0) return false;
  return FILE_EXTENSIONS.has(candidate.slice(dot).toLowerCase());
}

/**
 * Every filename in the repository, for resolving bare references.
 *
 * A bare `self-review.md` in a routing table is shorthand a reader resolves by
 * knowing the stack, and holding it to a full path would flag most of the
 * prose. What matters is that the name still names something: when a file is
 * renamed or deleted, every bare reference to it becomes a dead pointer, and
 * that is what this catches.
 */
function indexBasenames(dir, into = new Set()) {
  if (!existsSync(dir)) return into;
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) indexBasenames(full, into);
    else into.add(entry);
  }
  return into;
}

const BASENAMES = indexBasenames(REPO_ROOT);

/**
 * Extra roots a partial path may be relative to.
 *
 * The skills route with paths relative to their own directory, and provenance
 * notes elsewhere quote those same partial paths - `recon/landscape.md` means
 * the executor skill's file, wherever it is being mentioned from. Resolving
 * against each skill root is what makes those readable references rather than
 * findings.
 */
function resolutionRoots() {
  const roots = [join(REPO_ROOT, "library", "src"), join(REPO_ROOT, "library")];
  const skills = join(REPO_ROOT, ".claude", "skills");
  if (existsSync(skills)) {
    for (const entry of readdirSync(skills)) {
      const full = join(skills, entry);
      if (!statSync(full).isDirectory()) continue;
      roots.push(full);
      // A skill quotes its own files as `recon/landscape.md`, without the
      // references/ prefix, and other files quote them the same way.
      const references = join(full, "references");
      if (existsSync(references)) roots.push(references);
    }
  }
  return roots;
}

const EXTRA_ROOTS = resolutionRoots();

/**
 * Resolve a reference the way a reader would: relative to the file, then to
 * the skills directory, then to the repository root. A skill saying
 * `roblox-ui/references/blueprints.md` means the sibling skill, not a
 * subdirectory of itself.
 *
 * A reference carrying a slash is a claim about location and is held to it.
 * A bare filename only has to exist somewhere.
 */
function resolveReference(reference, fromFile) {
  const candidates = [
    resolve(dirname(fromFile), reference),
    resolve(join(REPO_ROOT, ".claude", "skills"), reference),
    resolve(REPO_ROOT, reference),
  ];
  if (candidates.some((candidate) => existsSync(candidate))) return true;
  if (EXTRA_ROOTS.some((root) => existsSync(resolve(root, reference)))) return true;
  if (reference.includes("/")) return false;
  return BASENAMES.has(reference);
}

function lintFile(path, findings) {
  const rel = relative(REPO_ROOT, path).split(sep).join("/");
  if (SKIP_FILES.has(rel)) return;
  const lines = readFileSync(path, "utf8").split(/\r?\n/);

  let inFence = false;

  for (const [index, line] of lines.entries()) {
    if (/^\s*```/.test(line)) {
      inFence = !inFence;
      continue;
    }
    // Code blocks hold shell commands and Luau, where a path is illustrative.
    if (inFence) continue;

    const report = (reference, kind) => {
      if (ALLOW.has(reference)) return;
      if (resolveReference(reference, path)) return;
      findings.push({
        file: rel,
        line: index + 1,
        code: kind,
        message: `${reference} does not resolve from ${rel}`,
      });
    };

    // 1. Markdown links, skipping anchors, URLs and mailto.
    for (const match of line.matchAll(/\[[^\]]*\]\(([^)\s]+)\)/g)) {
      const target = match[1].split("#")[0];
      if (!target || /^(https?:|mailto:|#)/.test(target)) continue;
      report(target, "E-LINK");
    }

    // 2. Backticked paths. Requires a slash or a known extension, so
    //    `UIListLayout` and `Enum.Font` are not mistaken for files.
    for (const match of line.matchAll(/`([^`\n]+)`/g)) {
      const raw = match[1].trim();
      if (!raw || /\s/.test(raw)) continue;
      if (/^(https?:|#)/.test(raw)) continue;
      if (!hasFileExtension(raw)) continue;
      // A bare extension-only token, or something that is plainly code.
      if (raw.startsWith(".") && !raw.includes("/")) continue;
      if (/[(){}<>*?"|]/.test(raw)) continue;
      report(raw.replace(/^\.\//, "").split("#")[0], "E-PATH");
    }
  }
}

function main() {
  const args = process.argv.slice(2);
  const asJson = args.includes("--json");
  const explicit = args.filter((a) => !a.startsWith("--"));

  let files;
  if (explicit.length) {
    files = explicit.flatMap((p) => {
      const full = existsSync(p) ? p : join(REPO_ROOT, p);
      if (!existsSync(full)) {
        console.error(`no such path: ${p}`);
        process.exitCode = 2;
        return [];
      }
      return statSync(full).isDirectory() ? walk(full) : [full];
    });
  } else {
    files = [...ROOTS.flatMap((root) => walk(root)), ...EXTRA_FILES.filter(existsSync)];
  }

  const findings = [];
  for (const file of files) lintFile(file, findings);

  if (asJson) {
    console.log(JSON.stringify({ findings }, null, 2));
  } else {
    findings.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
    for (const f of findings) console.log(`${f.file}:${f.line}  ${f.code}  ${f.message}`);
    console.log(`\n${files.length} files - ${findings.length} broken reference(s)`);
  }

  if (findings.length > 0) process.exitCode = 1;
}

main();
