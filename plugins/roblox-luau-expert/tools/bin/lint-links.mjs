#!/usr/bin/env node
// Check that every file this stack points at actually exists.
//
// The skills route by naming files - "see `references/value-persistence.md`",
// "run `tools/bin/verify-api.mjs`". A model following a dead pointer does not
// error; it improvises, which is the exact failure the stack exists to prevent.
// Prose linting cannot catch it because the name is perfectly well-formed.
//
// Two kinds of reference are checked:
//
//   1. Markdown links     [text](path/to/file.md)
//   2. Backticked paths   `references/foo.md`, `tools/bin/bar.mjs`
//
// The second is the one that matters. It is how the skills actually route, and
// it is invisible to every other tool here.
//
// Usage:
//   node tools/bin/lint-links.mjs [--json] [path...]
//
// Exit 1 on any broken reference.

import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, dirname, relative, resolve, sep } from "node:path";
import { REPO_ROOT } from "./lib/dump.mjs";

const ROOTS = [
  join(REPO_ROOT, ".claude", "skills"),
  join(REPO_ROOT, "docs"),
  join(REPO_ROOT, "library"),
  join(REPO_ROOT, "evals"),
];

const EXTRA_FILES = ["README.md", "AGENTS.md"].map((f) => join(REPO_ROOT, f));

const SKIP_DIRS = new Set(["node_modules", ".git"]);

// A changelog naming a file that was later renamed or deleted is accurate
// history, not a dead pointer. Linting it would force the past to be rewritten
// every time something moves.
// ui-pack.md is docs/portability/gpt/UIs/ concatenated into one uploadable
// file. Its relative references are correct where they were written and are
// linted there; re-checking them against the flattened copy's location only
// reports the flattening.
const SKIP_FILES = new Set([
  "docs/CHANGELOG.md",
  "docs/portability/gpt/knowledge/ui-pack.md",
  "docs/portability/gpt/knowledge/workflow-pack.md",
]);

// Extensions worth resolving. A backticked `Tokens.luau` is a reference; a
// backticked `Enum.Font` is not, and .Font is not in this list.
const FILE_EXTENSIONS = new Set([".md", ".luau", ".lua", ".mjs", ".ps1", ".json", ".txt", ".yaml", ".toml"]);

// Paths that name a real thing outside this repository, or a placeholder. Each
// needs a reason, the same rule the prose allowlist follows.
